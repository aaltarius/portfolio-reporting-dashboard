def get_language(settings: dict | None) -> str:
    if not isinstance(settings, dict):
        return "it"
    return str(settings.get("i18n", {}).get("language", "it")).lower()


def t(settings: dict | None, key: str, default: str) -> str:
    lang = get_language(settings)
    return TRANSLATIONS.get(lang, {}).get(key, default)
